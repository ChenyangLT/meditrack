## 十、常见问题

**问：清空数据和清除缓存有什么区别？**
答：「清除缓存」只删除可以重新生成的临时文件（已经不再使用的自定义铃声片段、提醒决策日志），不影响药品、服药记录和设置。「清空所有数据」会不可恢复地删除全部药品与服药记录。

**问：我把药盒上的名字填错了，能改吗？**
答：能。药品列表里点进去改，保存后不影响已经产生的历史记录——历史里的剂量是当时的快照。

**问：我吃了但忘了点「已服」，事后能补吗？**
答：能。「今日」里点那一条的「标记已服」，或者在「历史」里点对应日期的「补记」。

**问：半片怎么记？**
答：液体类药品的步进是 0.5；片剂按整数记。如果医嘱是半片，建议把剂量设置成 0.5 并把单位改为可分割的类型。

**问：免打扰时段里到点的药会不会被忘掉？**
答：不会。默认会顺延到时段结束后再提醒，也可以在设置里改为「只在通知栏静默显示」。已经在免打扰时段内服过的药不会被重复提醒。

**问：小组件不刷新？**
答：小组件的刷新由「设置 → 桌面小组件 → 刷新间隔」控制（10 秒到 10 分钟），并且需要「后台守护服务」处于开启状态。系统本身对小组件的刷新有 30 分钟的下限，所以不开启守护服务时最快约半小时一次。

**问：换了铃声，为什么听起来还是旧的？**
答：通知声音在系统里是「通道」级的，创建后由系统冻结。本应用的做法是每次换铃声都新建一个通知通道再删掉旧的，所以正常情况会立刻生效。如果仍然不对，到「设置 → 提醒与响铃 → 系统通知设置」里检查一下这个应用的通知分类有没有被手动改过。

**问：这个应用会把我的用药信息发出去吗？**
答：不会。详见《用户协议》第四条：应用只在本机保存数据，唯一的联网行为是检查更新（只发送一个公开的 GET 请求，不含任何你的信息），以及你自己点「去搜索」时打开浏览器。

**问：为什么应用要我读完两份文件才能用？**
答：因为这两份文件说的是这个应用**不**做什么——它不做诊断、不做用药建议、不能作为唯一的提醒保障。跳过它们等于在不知道这些的前提下把用药交给一个工具，这对谁都不好。
