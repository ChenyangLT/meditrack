# 药准时 使用说明

这份说明按「第一次使用」的顺序写下来。照着做一遍，提醒就能可靠工作；如果某一步没做，对应的后果写在每节最后。

## 一、第一次打开

1. **阅读并同意本页的两份文件**，两份都要滑动到底部才能勾选。
2. **同意后会进入权限引导页**。这里要求的三项权限都能显著提高提醒的可靠性，建议全部打开：
   - **通知权限**：没有它，应用无法在到点时提醒你，通知里的「已服 / 稍后 / 跳过」按钮也不会出现。
