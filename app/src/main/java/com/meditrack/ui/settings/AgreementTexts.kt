- **弹出红色的复查提醒**，内容就是你写的那句医嘱。它会一直留在通知栏和锁屏上，需要你点「我知道了」才会消失。
- **自动关闭这个药的复查提醒**，不会反复烦你。
- 同时**顺手关掉这个药的用药提醒**（因为它已经吃完了该复查了）。
- 如果你想开始新一轮（例如复查后医生说继续吃），到药品编辑页点「**开始新一轮**」，计数从 0 重新开始，提醒自动重新打开。
- 在还差若干次时（默认还差 3 次），会先来一条安静的预告，让你有时间挂号。

### 第二种：去搜索

在同一个「复查提醒」区域，点「**去搜索**」：

- 应用会打开你的浏览器，自动填好「**药品名 + 吃多久需要去复查**」并搜索。
- 你可以在设置里把问句改成别的（例如「长期吃有什么副作用」），也可以加一个后缀（例如「高血压」），让搜索更贴近你的情况。
- 可以选百度、必应或搜狗。
- **只有你按这个按钮时才会打开浏览器**，应用不会在后台自动搜索。

## 七、设置界面怎么用

设置页的每一类都是**折叠**的，点标题展开：

- **权限**：通知、精确闹钟、电池白名单的当前状态，缺哪个点哪个。
- **提醒与响铃**：总开关、响铃方式、铃声、震动、横幅。
- **提醒方式**：提前多久预告、免打扰时段、重复间隔、稍后时长。
- **复查提醒**：全局开关、提前预告次数、搜索用哪个引擎。
- **提醒可靠性**：自检频率、闹钟级提醒、后台守护服务、后台定期核对。这些是「为什么我的提醒没响」的答案所在。
- **适老与无障碍**：大字、高对比、简化模式，以及一键适老预设。
- **桌面小组件**：显示条数、刷新间隔、是否显示已服用的。
- **数据与备份**：导出 JSON / CSV、导入备份、备份文件夹、**清除缓存**、清空所有数据。
- **更新**：启动时检查更新（有新版本才会弹窗）、立即检查更新。
- **其他**：应用锁、多服确认、查看用户协议与使用说明。

## 八、为什么我的提醒没响？（按顺序排查）

1. **通知权限**是不是被关了？「设置 → 权限」里看状态。
2. **电池优化白名单**加了吗？没加的话，手机睡久了会限制后台。
3. **自启动 / 后台运行**：国产手机（小米、华为、OPPO、vivo、荣耀、魅族、一加等）通常还有一个厂商自己的「自启动管理」和「后台运行管理」，需要在系统设置里允许本应用。设置页底部有「去系统设置」的入口。
4. **守护服务**开着吗？「设置 → 提醒可靠性 → 后台守护服务」。开启后通知栏会有一条常驻通知，它本身不响不震，只是让应用的进程活着。
5. **看一下「最近的提醒决策」**（设置 → 提醒可靠性 下方）：它记录了每一次提醒的判定——是发出了、还是因为什么原因没发（例如「距离上次提醒还不够久」「已过服药宽限期」）。这是回答「8 点为什么没提醒我」最直接的证据。
6. **手动修复**：点「立即重新排定提醒」，会从数据库重新推导并重排全部闹钟。

