## 三、到点提醒时会看到什么

- **通知栏横幅 + 锁屏**：显示药品名、大致时间与剂量。点通知可以跳到今日列表的对应条目。
- **三个按钮**：
  - **已服**：记录为已服用，同时停止响铃、取消后续提醒。
  - **稍后 N 分钟**：推迟提醒。通知栏会留下一条「已推迟到几点」，到时间重新提醒你。
  - **跳过**：记录为本次跳过（不算漏服），不再提醒。
- **提前预告**：如果开启了「提前 N 分钟预告」，会先来一条安静的「还有 15 分钟：某某药」，让你先准备水。它只响一声，不会持续响。
- **持续响铃**：到点的那次提醒可以一直响到你处理为止。**响铃期间点上面任意一个按钮都会立刻安静下来**，并且当前这条提醒的响铃就此结束，不会在几秒后又响起来。

> 如果响铃的时候你按了电源键或调了音量，铃声不会停——这是有意的，闹钟级的提醒就该这样。要停就点通知上的三个按钮之一，或者通知里常驻的「停止响铃」。

## 四、让持续响铃合你的习惯

到「**设置 → 提醒与响铃**」：

- **响铃方式**
  - **只响一次**：和以前一样，响一声就停下。
  - **一直响到处理**（默认）：持续响，直到你点任意一个按钮。**建议保留这一项**，它是这个应用最不容易漏服的地方。
  - **响几次就停**：响固定次数，每次之间有间隔。
- **最多响多久**（默认 5 分钟）：一直响的安全上限。到了上限会自动安静，但**通知会留在通知栏**，你依然能看到并处理。
- **响铃次数 / 间隔**：只在「响几次就停」时生效。
- **手机静音时仍然响铃**：关掉时，手机静音或处于免打扰就只显示通知不发声。

